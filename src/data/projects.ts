export const projects: Project[] = data.map((p) => {
  const shots = (manifest[p.slug] ?? []).map((s) => ({
    ...s,
    caption: captions[p.slug]?.[s.name] ?? p.title,
  }));
  if (p.cover) {
    const i = shots.findIndex((s) => s.name === p.cover);
    if (i > 0) shots.unshift(...shots.splice(i, 1));
  }
  return { ...p, screenshots: shots };
});

export function getProject(slug: string) {
  return projects.find((p) => p.slug === slug);
}
